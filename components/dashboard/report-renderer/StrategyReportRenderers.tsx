const StatusBadge = ({ text, type }: { text: string; type?: "success" | "warning" | "info" | "default" | "purple" | "orange" | "blue" }) => {
  const styles = {
    success: "bg-green-50 text-green-700 border-green-200",
    warning: "bg-amber-50 text-amber-700 border-amber-200",
    info: "bg-blue-50 text-blue-700 border-blue-200",
    purple: "bg-purple-50 text-purple-700 border-purple-200",
    orange: "bg-orange-50 text-orange-700 border-orange-200",
    blue: "bg-blue-50 text-blue-700 border-blue-200",
    default: "bg-gray-50 text-gray-700 border-gray-200",
  };
  
  const icons = {
    success: <CheckCircle2 size={12} />,
    warning: <AlertCircle size={12} />,
    info: <Info size={12} />,
    purple: <Sparkles size={12} />,
    orange: <Flame size={12} />,
    blue: <Info size={12} />,
    default: null,
  };
  
  return (
    <span className={`inline-flex items-center gap-1 px-2 py-1 rounded-md text-xs font-medium border ${styles[type || "default"]}`}>
      {type && icons[type as keyof typeof icons]}
      {text}
    </span>
  );
};

